const char* LookupPinyin(unsigned code) {
    size_t low = 0;
    size_t high = kPinyinCount;
    while (low < high) {
        size_t mid = (low + high) / 2;
        if (kPinyinTable[mid].code < code) {
            low = mid + 1;
        } else {
            high = mid;
        }
    }
    if (low < kPinyinCount && kPinyinTable[low].code == code) {
        return kPinyinTable[low].syllable;
    }
    return nullptr;
}

